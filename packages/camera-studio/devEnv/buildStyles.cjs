const fs = require('node:fs/promises')
const path = require('node:path')
const lightTheme = require('../../studio/src/lightTheme.json')
const postcss = require('postcss')
const tailwindcss = require('tailwindcss')
const nesting = require('tailwindcss/nesting')

async function buildStyles() {
  const packageRoot = path.resolve(__dirname, '..')
  const dir = path.join(packageRoot, 'src/styles')
  const files = (await fs.readdir(dir))
    .filter((file) => file.endsWith('.css'))
    .sort()
  const sources = await Promise.all(
    files.map((file) => fs.readFile(path.join(dir, file), 'utf8')),
  )
  // Emit only component rules declared in our stylesheet. The host's CSS and
  // Shadow DOM never receive Tailwind's element reset or unscoped utilities.
  const lightThemeCss = Object.entries(lightTheme)
    .map(([property, value]) => `  ${property}: ${value};`)
    .join('\n')
  const styles = [
    `:root:where([data-camera-studio-color-mode='light']) {\n${lightThemeCss}\n}`,
    ...sources,
  ]
  const result = await postcss([
    nesting,
    tailwindcss({
      content: [path.join(packageRoot, 'src/**/*.{ts,tsx}')],
      corePlugins: {preflight: false},
    }),
  ]).process(styles.join('\n'), {from: path.join(dir, 'index.css')})
  const target = path.join(dir, 'cameraStyles.generated.ts')
  const output =
    '// Generated by pnpm build:styles. Edit the CSS sources in this directory.\n' +
    '// prettier-ignore\n' +
    'export default ' +
    JSON.stringify(result.css) +
    '\n'
  if (process.argv.includes('--check')) {
    if ((await fs.readFile(target, 'utf8')) !== output) {
      throw new Error('Camera Studio CSS is stale. Run pnpm build:styles.')
    }
  } else {
    await fs.writeFile(target, output)
  }
}

buildStyles().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
